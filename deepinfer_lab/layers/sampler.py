"""Deterministic, batch-invariant token sampler.

Sampling uses the Gumbel-max trick: argmax(logits / T + g) with g ~ Gumbel(0, 1) draws a sample
from softmax(logits / T). The Gumbel noise for a row is generated by Philox keyed on
hash(seq_seed, position), so a sequence's sample depends only on its own logits, seed and
position -- never on which other sequences share the batch, the row order, or whether the step
was recomputed after preemption.
"""

from __future__ import annotations

from dataclasses import dataclass

import torch
import triton
import triton.language as tl

_MASK64 = (1 << 64) - 1


def mix_seed(seq_seed: int, position: int) -> int:
    """SplitMix64-style hash of (seed, position), truncated to a non-negative int63."""
    z = (seq_seed + (position + 1) * 0x9E3779B97F4A7C15) & _MASK64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & _MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & _MASK64
    return (z ^ (z >> 31)) >> 1


@triton.jit
def _gumbel_noise_kernel(Out, Seeds, vocab_size, stride_out, BLOCK: tl.constexpr):
    row = tl.program_id(0)
    cols = tl.program_id(1) * BLOCK + tl.arange(0, BLOCK)
    seed = tl.load(Seeds + row)
    u = tl.rand(seed, cols)
    u = tl.maximum(u, 1e-20)
    g = -tl.log(-tl.log(u))
    tl.store(Out + row * stride_out + cols, g, mask=cols < vocab_size)


def gumbel_noise(seeds: torch.Tensor, vocab_size: int) -> torch.Tensor:
    out = torch.empty(seeds.shape[0], vocab_size, dtype=torch.float32, device=seeds.device)
    block = 4096
    _gumbel_noise_kernel[(seeds.shape[0], triton.cdiv(vocab_size, block))](out, seeds, vocab_size, out.stride(0), BLOCK=block)
    return out


@triton.jit
def _argmax_first(scores):
    # Triton's argmax does not give NaNs the priority that torch.argmax does.
    is_nan = scores != scores
    nan_index = tl.min(tl.where(is_nan, tl.arange(0, scores.shape[0]), 0x7FFFFFFF), 0)
    value, index = tl.max(tl.where(is_nan, -float("inf"), scores), 0, return_indices=True)
    has_nan = nan_index != 0x7FFFFFFF
    return tl.where(has_nan, float("nan"), value), tl.where(has_nan, nan_index, index)


@triton.jit
def _sample_tiles(Logits, Temperatures, Greedy, Seeds, Values, Indices, vocab, row_stride, col_stride,
                  NUM_TILES: tl.constexpr, BLOCK: tl.constexpr):
    row, tile = tl.program_id(0), tl.program_id(1)
    cols = tile * BLOCK + tl.arange(0, BLOCK)
    scores = tl.load(Logits + row * row_stride + cols * col_stride, cols < vocab, other=-float("inf"))
    if not tl.load(Greedy + row):
        temperature = tl.load(Temperatures + row)
        seed = tl.load(Seeds + row)
        u = tl.maximum(tl.rand(seed, cols), 1e-20)
        scores = tl.div_rn(scores, temperature) - tl.log(-tl.log(u))
    value, index = _argmax_first(scores)
    tl.store(Values + row * NUM_TILES + tile, value)
    tl.store(Indices + row * NUM_TILES + tile, tile * BLOCK + index)


@triton.jit
def _sample_finish(Values, Indices, Out, NUM_TILES: tl.constexpr, BLOCK: tl.constexpr):
    row = tl.program_id(0)
    tiles = tl.arange(0, BLOCK)
    values = tl.load(Values + row * NUM_TILES + tiles, tiles < NUM_TILES, other=-float("inf"))
    # Tiles and token indices are ordered, so leftmost ties match torch.argmax, including NaNs.
    _, tile = _argmax_first(values)
    tl.store(Out + row, tl.load(Indices + row * NUM_TILES + tile))


def sample_unfiltered(logits: torch.Tensor, t: SamplingTensors) -> torch.Tensor:
    """Reduce Gumbel scores in two passes without materializing [batch, vocab] noise or scaled logits."""
    rows, vocab = logits.shape
    block = min(4096, triton.next_power_of_2(vocab))
    tiles = triton.cdiv(vocab, block)
    values = torch.empty(rows, tiles, device=logits.device, dtype=torch.float32)
    indices = torch.empty(rows, tiles, device=logits.device, dtype=torch.int32)
    out = torch.empty(rows, device=logits.device, dtype=torch.int64)
    _sample_tiles[(rows, tiles)](
        logits, t.temperatures, t.greedy, t.seeds, values, indices, vocab, *logits.stride(),
        NUM_TILES=tiles, BLOCK=block,
    )
    _sample_finish[(rows,)](values, indices, out, NUM_TILES=tiles, BLOCK=triton.next_power_of_2(tiles))
    return out


@dataclass
class SamplingTensors:
    temperatures: torch.Tensor  # [B] float32; 1.0 for greedy rows.
    greedy: torch.Tensor  # [B] bool
    top_k: torch.Tensor  # [B] int64; vocab_size when disabled.
    top_p: torch.Tensor  # [B] float32
    seeds: torch.Tensor  # [B] int64, mix_seed(seq_seed, position of the sampled token).
    all_greedy: bool
    need_top_k_top_p: bool


def apply_top_k_top_p(logits: torch.Tensor, top_k: torch.Tensor, top_p: torch.Tensor) -> torch.Tensor:
    """Masks logits outside the per-row top-k / nucleus set (ties at the cutoff are kept)."""
    sorted_logits, _ = logits.sort(dim=-1, descending=True)
    vocab_size = logits.shape[-1]
    k_index = (top_k.clamp(1, vocab_size) - 1).unsqueeze(1)
    ranks = torch.arange(vocab_size, device=logits.device).unsqueeze(0)
    sorted_logits = sorted_logits.masked_fill(ranks > k_index, float("-inf"))
    probs = sorted_logits.softmax(dim=-1)
    # Keep the smallest prefix whose cumulative probability reaches top_p (always keeps rank 0).
    keep = (probs.cumsum(dim=-1) - probs) < top_p.unsqueeze(1)
    num_keep = keep.sum(dim=-1, keepdim=True).clamp(max=k_index + 1)
    cutoff = sorted_logits.gather(1, num_keep - 1)
    return logits.masked_fill(logits < cutoff, float("-inf"))


class Sampler(torch.nn.Module):
    @torch.inference_mode()
    def forward(self, logits: torch.Tensor, t: SamplingTensors) -> torch.Tensor:
        logits = logits.float()
        if t.all_greedy:
            return logits.argmax(dim=-1)
        if not t.need_top_k_top_p:
            return sample_unfiltered(logits, t)
        scaled = apply_top_k_top_p(logits / t.temperatures.unsqueeze(1), t.top_k, t.top_p)
        sampled = (scaled + gumbel_noise(t.seeds, logits.shape[-1])).argmax(dim=-1)
        return torch.where(t.greedy, logits.argmax(dim=-1), sampled)
